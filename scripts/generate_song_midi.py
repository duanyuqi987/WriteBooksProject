import mido
from mido import Message, MetaMessage, MidiFile, MidiTrack
import os

TICKS = 480
BPM = 72

# 1=D4: 简谱→MIDI
JP = {
    '1': 62, '2': 64, '3': 66, '4': 67, '5': 69, '6': 71, '7': 73,
    "1'": 74, "2'": 76, "3'": 78, "4'": 79, "5'": 81, "6'": 83,
}

# 和弦→MIDI (钢琴中低音区)
CHORDS = {
    '6m': [59, 62, 66],   # Bm: B3 D4 F#4
    '4':  [55, 59, 62],   # G:  G3 B3 D4
    '1':  [50, 54, 57],   # D:  D3 F#3 A3
    '5':  [57, 61, 64],   # A:  A3 C#4 E4
    '2m': [52, 55, 59],   # Em: E3 G3 B3
    '#5': [58, 61, 64],   # A#dim
}


def b2t(beats):
    return int(beats * TICKS)


