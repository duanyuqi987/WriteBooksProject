# 旋律数据: 列表的列表, 每个子列表=1小节=4拍
# 每项 (简谱符号, 拍数)
# ═══════════════════════════════════════════

M = []  # [[(note, dur), ...], ...] 每元素一小节


def bar(*notes):
    """添加一小节。验证精确 4 拍。"""
    total = sum(d for _, d in notes)
    if abs(total - 4.0) > 0.02:
        raise ValueError(f"小节拍数={total}, 应为4.0: {notes}")
    M.append(list(notes))


