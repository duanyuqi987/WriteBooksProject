# 截断或补齐和弦序列以匹配旋律小节数
if len(SEQ) < NM:
    SEQ = list(SEQ) + ['6m'] * (NM - len(SEQ))
elif len(SEQ) > NM:
    SEQ = SEQ[:NM]


# ═══════════════════════════════════════════
# MIDI 生成
# ═══════════════════════════════════════════

def generate_midi(melody, chord_seq, path):
    mid = MidiFile(ticks_per_beat=TICKS)

    # Track 0: 和弦伴奏
    chord_track = MidiTrack()
    mid.tracks.append(chord_track)
    chord_track.append(MetaMessage('set_tempo', tempo=mido.bpm2tempo(BPM), time=0))
    chord_track.append(Message('program_change', program=0, time=0))

    # 写入和弦 (每小节两个和弦击: 第1拍+第3拍)
    beat = 0
    for sym in chord_seq:
        notes = CHORDS[sym]
        # 第1拍
        start_tick = b2t(beat)
        base_time = _track_abs(chord_track)
        if start_tick > base_time:
            chord_track.append(Message('note_on', note=notes[0], velocity=60, time=start_tick - base_time))
        else:
            chord_track.append(Message('note_on', note=notes[0], velocity=60, time=0))
        for n in notes[1:]:
            chord_track.append(Message('note_on', note=n, velocity=55, time=0))
        # 第3拍松键
        off_time = b2t(beat + 2)
        cur = _track_abs(chord_track)
        chord_track.append(Message('note_off', note=notes[0], velocity=0, time=off_time - cur))
        for n in notes[1:]:
            chord_track.append(Message('note_off', note=n, velocity=0, time=0))
        # 第3拍再击
        beat3_tick = b2t(beat + 2)
        cur = _track_abs(chord_track)
        chord_track.append(Message('note_on', note=notes[0], velocity=48, time=beat3_tick - cur))
        for n in notes[1:]:
            chord_track.append(Message('note_on', note=n, velocity=42, time=0))
        # 第4拍末松
        off2_time = b2t(beat + 4)
        cur = _track_abs(chord_track)
        chord_track.append(Message('note_off', note=notes[0], velocity=0, time=off2_time - cur))
        for n in notes[1:]:
            chord_track.append(Message('note_off', note=n, velocity=0, time=0))
        beat += 4

    # Track 1: 主旋律
    mel_track = MidiTrack()
    mid.tracks.append(mel_track)
    mel_track.append(Message('program_change', program=74, time=0))  # 长笛音色

    mel_abs = 0
    for note_sym, dur in melody:
        midi_note = JP[note_sym]
        dur_ticks = b2t(dur)

        mel_track.append(Message('note_on', note=midi_note, velocity=88, time=0))
        mel_track.append(Message('note_off', note=midi_note, velocity=0, time=dur_ticks))
        mel_abs += dur_ticks

    mid.save(path)
    return path


def _track_abs(track):
    t = 0
    for msg in track:
        t += msg.time
    return t


# ═══════════════════════════════════════════
# 主程序
# ═══════════════════════════════════════════

def main():
    total_beats = sum(d for _, d in MELODY)
    duration_sec = total_beats / BPM * 60
    print(f"旋律: {len(MELODY)} 个音符, {len(M)} 小节, {total_beats:.0f} 拍, {duration_sec:.0f} 秒 ({duration_sec/60:.1f} 分钟)")
    print(f"和弦: {len(SEQ)} 小节")

    # 验证每小节精确 4 拍
    issues = 0
    for i, measure in enumerate(M):
        s = sum(d for _, d in measure)
        if abs(s - 4.0) > 0.02:
            print(f"  !! 小节{i+1}: {s:.2f} 拍")
            issues += 1
    if issues == 0:
        print("  All measures exact 4/4 - OK")

    out = os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        'docs', '2026-05-27', '小说', '后来我们笑着走过',
        '后来我们笑着走过.mid'
    )
    os.makedirs(os.path.dirname(out), exist_ok=True)
    generate_midi(MELODY, SEQ, out)
    print(f"\nMIDI: {out}")


if __name__ == '__main__':
    main()
