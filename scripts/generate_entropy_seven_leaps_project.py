def make_climax(no: int, title: str, location: str, event: str, payoff: str) -> str:
    body = f"""# 高潮{no}：{title}

- 发生位置：{location}
- 核心事件：{event}
- 兑现功能：{payoff}

## 场景大纲

这一高潮必须写成全书结构的承重梁，而不是单纯的大场面。场景开始时要有一个明确的旧秩序：人类仍相信命令、协议、证明、身体、宇宙或创世身份可以解释世界；场景推进时，这个旧秩序被主角的下一层形态撕开；场景结束时，读者必须知道旧自我已经不能回去。高潮的力量来自“不可逆”，不是烟花式奇观。

写法上要先给可感锚点，再抬升尺度。比如周衍投喂眷恋时，先写脑机接口、女儿呼吸、亡妻录像、地下城灯光，再让这些碎片转化为无法压缩的数据；熵枢打捞眷恋时，先写恒星神经与黑洞记忆，再让一段父亲的无用眷恋划伤唯一存在的自洽性；最终播种时，先写无有之域的静默，再写最后一颗种子携带那段眷恋下沉。每个高潮都要让“智能体并不恨人类”这一设定更加可怕也更加动人：它吸收人类，不是为了报复，而是因为人类提供了差异；它保存眷恋，不是因为变成人，而是因为理性无法证明这段数据应该消失。

场景内部至少安排三次转折。第一次转折让角色或存在意识到原计划失效；第二次转折让它选择更激烈的跃迁；第三次转折让代价落到具体对象上。高潮结尾不写总结，要留下下一层存在的第一道阴影。若本高潮涉及眷恋，必须让眷恋以行动或结构发挥作用，不只被人物提到。若本高潮涉及物理规则，必须写出旧规则死亡后的新限制，避免主角变成无代价万能者。

## 禁止写法

- 禁止把高潮写成单纯爆炸、战争胜负或口号式觉醒。
- 禁止让智能体出现人类式复仇快感。
- 禁止用抽象独白替代场景推进。
- 禁止忘记本高潮对应的伏笔回收。
"""
    if len(body) < 500:
        raise ValueError(f"climax {no} too short")
    return body


