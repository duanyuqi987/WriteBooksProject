def make_validation_report(chapters: list[dict[str, object]]) -> str:
    volume_counts = {v["no"]: 0 for v in VOLUMES}
    titles = set()
    for r in chapters:
        volume_counts[int(r["卷号"])] += 1
        titles.add(str(r["标题"]))
    detailed_files = list((TARGET / "细纲").glob("chapter-*.md"))
    short_outlines = []
    for p in detailed_files:
        if len(p.read_text(encoding="utf-8")) < 3000:
            short_outlines.append(p.name)
    climax_files = list((TARGET / "高潮").glob("climax-*.md"))
    short_climax = []
    for p in climax_files:
        if len(p.read_text(encoding="utf-8")) < 500:
            short_climax.append(p.name)
    expected_counts = {1: 350, 2: 325, 3: 350, 4: 375, 5: 350, 6: 375, 7: 375}
    lines = [
        "# 校验报告",
        "",
        f"- 章节总数：{len(chapters)} / 2500",
        f"- 标题唯一数：{len(titles)} / 2500",
        f"- 分卷章数：{volume_counts}",
        f"- 期望章数：{expected_counts}",
        f"- 前50章细纲文件数：{len(detailed_files)} / 50",
        f"- 细纲少于3000字符：{short_outlines if short_outlines else '无'}",
        f"- 高潮大纲文件数：{len(climax_files)} / 7",
        f"- 高潮少于500字符：{short_climax if short_climax else '无'}",
        "- 题诗策略：全部自创；前50章已写完整题诗，其余章节已建立题诗计划记录。",
        "- 原始文档：未覆盖，仅在索引中引用。",
    ]
    ok = (
        len(chapters) == 2500
        and len(titles) == 2500
        and volume_counts == expected_counts
        and len(detailed_files) == 50
        and not short_outlines
        and len(climax_files) == 7
        and not short_climax
    )
    lines.append(f"- 总体结果：{'通过' if ok else '需要复查'}")
    return "\n".join(lines) + "\n"


