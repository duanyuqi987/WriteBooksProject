def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.replace("\r\n", "\n"), encoding="utf-8")


def csv_write(path: Path, rows: list[dict[str, object]], fieldnames: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def md_table(headers: list[str], rows: list[list[object]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join(["---"] * len(headers)) + " |"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def volume_ranges() -> list[dict[str, object]]:
    start = 1
    out = []
    for v in VOLUMES:
        item = dict(v)
        item["start"] = start
        item["end"] = start + v["chapters"] - 1
        out.append(item)
        start = item["end"] + 1
    return out


def chapter_title(volume: dict[str, object], chapter_no: int, local_no: int) -> str:
    if chapter_no <= 50:
        return FIRST_50[chapter_no - 1][0]
    motif = volume["motifs"][(local_no - 1) % len(volume["motifs"])]
    verbs = ["初醒", "裂响", "低语", "回潮", "折光", "暗涌", "证词", "坠落", "重构", "余震"]
    verb = verbs[((local_no - 1) // len(volume["motifs"])) % len(verbs)]
    phase = phase_name(volume["no"], local_no)
    return f"{volume['short']}·{phase}·{motif}{verb}{local_no:03d}"


